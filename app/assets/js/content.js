  function tenGodOf(stem, dayStem) { // 천간 기준 십성
    const oe = E.STEM_ELEM[stem], de = E.STEM_ELEM[dayStem];
    const same = E.STEM_YANG[stem] === E.STEM_YANG[dayStem];
    const ei = E.ELEMS.indexOf(de);
    if (oe === de) return same ? "비견" : "겁재";
    if (E.ELEMS[(ei + 1) % 5] === oe) return same ? "식신" : "상관";
    if (E.ELEMS[(ei + 2) % 5] === oe) return same ? "편재" : "정재";
    if (E.ELEMS[(ei + 3) % 5] === oe) return same ? "편관" : "정관";
    return same ? "편인" : "정인";
  }

