  const ELEM_CLASH = { 木: "土", 土: "水", 水: "火", 火: "金", 金: "木" };

  function pairRel(a, b) {
    if (a === b) return "same";
    if (ELEM_GEN[a] === b) return "give";     // a가 b를 생
    if (ELEM_GEN[b] === a) return "receive";
    if (ELEM_CLASH[a] === b) return "clash";
    return "none";
  }
  function hasPair(list, a, b) {
    return list.some(p => (p[0] === a && p[1] === b) || (p[0] === b && p[1] === a));
  }
  function samhapOf(a, b) {
    return SAMHAP.some(group => group.includes(a) && group.includes(b));
  }

